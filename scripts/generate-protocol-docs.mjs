import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { codexSchemaCliVersion } from '../src/protocol/schema-version.ts';

const root = new URL('../', import.meta.url);
const read = path => readFile(new URL(path, root), 'utf8');
const output = new URL('docs/api/json-rpc.md', root);

function methods(source, label) {
  const entries = [...source.matchAll(/^  "([^"]+)": \{ params: (.*); result: (.*) \};$/gm)]
    .map(([, method, params, result]) => ({ method, params, result }));
  if (!entries.length || new Set(entries.map(entry => entry.method)).size !== entries.length) {
    throw new Error(`Empty or duplicate ${label} inventory; check the method-map format.`);
  }
  return entries;
}
const requests = methods(await read('src/protocol/method-map.ts'), 'client request');
const serverRequests = methods(await read('src/protocol/server-request-map.ts'), 'server request');
const notifications = [...(await read('src/protocol/generated/ServerNotification.ts'))
  .matchAll(/\{ "method": "([^"]+)"/g)].map(([, method]) => method);
if (!notifications.length || new Set(notifications).size !== notifications.length) {
  throw new Error('Empty or duplicate notification inventory; check the generated union format.');
}
const code = text => `\`${text.replaceAll('|', '\\|')}\``;
const table = rows => [
  '| Method | Parameters | Result |',
  '| --- | --- | --- |',
  ...rows.map(({ method, params, result }) => `| ${code(method)} | ${code(params)} | ${code(result)} |`),
].join('\n');
const markdown = `<!-- Generated by scripts/generate-protocol-docs.mjs. Do not edit by hand. -->
# Protocol inventory

This inventory follows the checked-in **${codexSchemaCliVersion}** schema, including experimental APIs. Every listed method is typed at the client boundary; availability depends on the running Codex server and its configuration.

Run \`npm run generate:rpc\` after schema regeneration. \`npm run check:rpc\` detects documentation drift without launching Codex.

## Summary

| Direction | Count | Client API |
| --- | ---: | --- |
| Client requests | ${requests.length} | \`request(method, params)\` |
| Server notifications | ${notifications.length} | \`onNotification(method, listener)\` |
| Server requests | ${serverRequests.length} | \`onServerRequest(method, handler)\` |

## Client requests

${table(requests)}

## Server notifications

| Method |
| --- |
${notifications.map(method => `| ${code(method)} |`).join('\n')}

## Server requests

${table(serverRequests)}

Parameter and result names refer to exported generated protocol types. Import them from \`@korus-dev/codex-sdk\` or the [types-only subpaths](/api/#types-only-subpaths). The client routes these messages; your app owns their presentation, approval policy, and any state derived from notifications.
`;

if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8').catch(() => '') !== markdown) {
    console.error('Protocol inventory is stale. Run npm run generate:rpc.');
    process.exitCode = 1;
  } else console.log('Protocol inventory matches the checked-in schema.');
} else {
  await writeFile(output, markdown);
  console.log(`Wrote ${fileURLToPath(output)}.`);
}
